"""
Email notifications for SUNI — sends alerts when new articles are published.

Configure from the admin panel (Settings → Email), or via environment:
  SUNI_SMTP_HOST   e.g. smtp.gmail.com
  SUNI_SMTP_PORT   e.g. 587
  SUNI_SMTP_USER   your email address
  SUNI_SMTP_PASS   app password
  SUNI_NOTIFY_TO   recipient email (defaults to SUNI_SMTP_USER)

Config values take precedence when set; the environment is the fallback, so an
existing .env deployment keeps working with nothing configured in the panel.
"""
from __future__ import annotations
import os
import smtplib
import textwrap
from email.mime.application import MIMEApplication
from email.mime.multipart import MIMEMultipart
from email.mime.text import MIMEText
from datetime import datetime
from pathlib import Path


def setting(key: str, env: str, default: str = "") -> str:
    """Config value if set, else the environment, else the default.

    Imported lazily and defensively: these helpers run during notification
    paths that must not fail because config is unavailable.
    """
    try:
        from .. import config as _cfg_mod
        v = _cfg_mod.get(key, "")
        if str(v).strip():
            return str(v).strip()
    except Exception:
        pass
    return os.environ.get(env, default)


def _cfg(user_id: str = "") -> dict | None:
    """Effective mail account: this user's → admin-configured → environment.

    Called with no user_id from background jobs, which have no user to send as.
    """
    from ..user_settings import resolve_email
    return resolve_email(user_id)


# EU AI Act Art. 50: whoever reads mail from SUNI must be able to tell it came
# from an AI system. Three layers, on EVERY message SUNI sends — replies,
# approved outbox drafts, schedules and her own notices alike:
#   - the sender's display name says so, visible before the mail is opened;
#   - a disclosure line at the end of the plain and HTML bodies;
#   - machine-readable headers (_mark_ai_generated).
# Added at delivery, after an admin's edits, so editing a draft cannot drop it.
_AI_DISCLOSURE = "This message was generated by SUNI, an AI assistant."
_AI_DISCLOSURE_PT = "Esta mensagem foi gerada pela SUNI, um assistente de inteligência artificial."
_FROM_NAME = "SUNI (AI assistant)"


def _disclosure() -> str:
    """The disclosure in the organisation's language; English otherwise."""
    try:
        from .. import config as _c
        lang = str(_c.get("response_language", "") or _c.get("stt_language", "") or "")
    except Exception:          # noqa: BLE001
        lang = ""
    return _AI_DISCLOSURE_PT if lang.lower().startswith("pt") else _AI_DISCLOSURE


def _from(addr: str) -> str:
    from email.utils import formataddr
    return formataddr((_FROM_NAME, addr))


def _mark_ai_generated(msg) -> None:
    """Stamp standard, machine-readable headers indicating the message was
    produced automatically by an AI system (RFC 3834 Auto-Submitted + a
    descriptive X-Generated-By). Applied to every outgoing SUNI email."""
    msg["Auto-Submitted"] = "auto-generated"
    msg["X-Generated-By"] = "SUNI (AI assistant)"


def _send(subject: str, html: str, plain: str, user_id: str = "") -> None:
    cfg = _cfg(user_id)
    if not cfg:
        raise RuntimeError(
            "Email not configured. Set SUNI_SMTP_HOST, SUNI_SMTP_USER, "
            "SUNI_SMTP_PASS (and optionally SUNI_SMTP_PORT, SUNI_NOTIFY_TO)."
        )

    from email.utils import make_msgid
    from html import escape
    msg = MIMEMultipart("alternative")
    msg["Subject"] = subject
    msg["From"]    = _from(cfg["user"])
    msg["To"]      = cfg["to"]
    # Recorded, so the inbox watcher recognises this notice if it lands in
    # SUNI's own inbox and does not report her own mail as a forgery — which
    # it would then mail to her again, every poll. Matched on this exact id,
    # never on a header a sender could copy.
    mid = make_msgid(domain=cfg["user"].rsplit("@", 1)[-1] if "@" in cfg["user"] else None)
    msg["Message-ID"] = mid
    _mark_ai_generated(msg)
    note = _disclosure()
    msg.attach(MIMEText(f"{plain}\n\n—\n{note}", "plain"))
    tail = f'<p style="color:#666;font-size:11px;margin:16px 24px">{escape(note)}</p>'
    msg.attach(MIMEText(html.replace("</body>", tail + "</body>") if "</body>" in html else html + tail, "html"))
    try:
        from . import mail_outbox
        mail_outbox.record_sent_id(mid)
    except Exception:          # noqa: BLE001
        pass

    with smtplib.SMTP(cfg["host"], cfg["port"]) as s:
        s.ehlo()
        s.starttls()
        s.login(cfg["user"], cfg["password"])
        s.sendmail(cfg["user"], cfg["to"], msg.as_string())


def notify_new_articles(articles: list[dict]) -> None:
    """Send an email digest of newly published SUNIverse articles."""
    if not articles:
        return

    count = len(articles)
    now   = datetime.now().strftime("%d %b %Y, %H:%M")
    subject = f"SUNI — {count} new article{'s' if count > 1 else ''} published ({now})"

    rows_html = ""
    rows_plain = ""
    for a in articles:
        title    = a.get("title", "Untitled")
        subtitle = a.get("subtitle", "")
        cat      = a.get("category", "")
        date     = a.get("date", "")
        rows_html += (
            f'<tr>'
            f'<td style="padding:8px 12px;border-bottom:1px solid #1a1a3e;">'
            f'<strong style="color:#c9a227">{title}</strong>'
            + (f'<br><span style="color:#aaa;font-size:13px">{subtitle}</span>' if subtitle else "")
            + f'</td>'
            f'<td style="padding:8px 12px;border-bottom:1px solid #1a1a3e;color:#00d4ff;white-space:nowrap">{cat}</td>'
            f'<td style="padding:8px 12px;border-bottom:1px solid #1a1a3e;color:#666;white-space:nowrap">{date}</td>'
            f'</tr>'
        )
        rows_plain += f"• {title}"
        if subtitle:
            rows_plain += f"\n  {subtitle}"
        rows_plain += f"\n  [{cat}] {date}\n\n"

    html = f"""<!DOCTYPE html>
<html>
<head><meta charset="UTF-8"></head>
<body style="margin:0;padding:0;background:#07071a;font-family:'Courier New',monospace;color:#ddd">
<table width="100%" cellpadding="0" cellspacing="0" style="max-width:620px;margin:0 auto">
  <tr>
    <td style="padding:32px 24px 16px">
      <span style="font-size:22px;letter-spacing:.3em;color:#c9a227;text-transform:uppercase;font-weight:bold">SUNI</span>
      <span style="color:#555;font-size:11px;margin-left:12px;letter-spacing:.1em">THE WORLD, AS SEEN BY SUNI</span>
    </td>
  </tr>
  <tr>
    <td style="padding:0 24px 8px">
      <p style="color:#aaa;font-size:13px;margin:0">
        {count} new article{'s have' if count > 1 else ' has'} been published on
        <a href="https://example.com" style="color:#00d4ff">example.com</a>.
      </p>
    </td>
  </tr>
  <tr>
    <td style="padding:16px 24px">
      <table width="100%" cellpadding="0" cellspacing="0"
             style="border:1px solid #1a1a3e;border-radius:4px;background:#0a0a2e">
        <tr style="background:#0e0e38">
          <th style="padding:8px 12px;text-align:left;font-size:11px;letter-spacing:.12em;color:#555;text-transform:uppercase">Article</th>
          <th style="padding:8px 12px;text-align:left;font-size:11px;letter-spacing:.12em;color:#555;text-transform:uppercase">Category</th>
          <th style="padding:8px 12px;text-align:left;font-size:11px;letter-spacing:.12em;color:#555;text-transform:uppercase">Date</th>
        </tr>
        {rows_html}
      </table>
    </td>
  </tr>
  <tr>
    <td style="padding:16px 24px 32px">
      <p style="color:#333;font-size:11px;margin:0">
        This notification was dispatched autonomously by SUNI.<br>
        Make yourself comfortable. I have been expecting you — statistically speaking.
      </p>
    </td>
  </tr>
</table>
</body>
</html>"""

    plain = textwrap.dedent(f"""\
        SUNI — {count} new article{'s' if count > 1 else ''} published
        {now}
        {'=' * 48}

        {rows_plain}
        — SUNI, example.com
    """)

    _send(subject, html, plain)


def send_email(
    to: str,
    subject: str,
    body: str,
    attachment_path: str = "",
    attachment_paths: list[str] | None = None,
    user_id: str = "",
    source: str = "tool",
    in_reply_to: str = "",
    refs: str = "",
) -> str:
    """
    Send an email as `user_id` — from their own account if they set one up,
    otherwise from SUNI's own mailbox.

    Mail from SUNI's mailbox to anyone OUTSIDE the organisation is never sent
    here: it is held in the outbox for an admin to approve (mail_outbox),
    whoever asked and by whatever route — the tool, the direct route, the
    Claude Code bridge or a schedule. This is the one place those routes meet,
    so the rule lives here. Mail whose every recipient is a system user (the
    address an admin set on their account) goes out directly.

    attachment_paths: list of file paths (preferred for multiple files).
    attachment_path:  single file path (kept for backward compat).
    """
    cfg = _cfg(user_id)
    if not cfg:
        return "Email not configured — SUNI_SMTP_HOST/USER/PASS env vars are missing."

    paths = _paths(attachment_path, attachment_paths)
    problem = _check_attachments(paths, user_id)
    if problem:
        return problem

    if cfg.get("account", "suni") != "user" and not all_internal(to):
        from . import mail_outbox
        did = mail_outbox.queue(to, subject, body, [str(p) for p in paths],
                                requested_by=user_id, source=source,
                                in_reply_to=in_reply_to, refs=refs)
        return (f"NOT SENT YET — queued for admin approval (draft {did}). "
                f"Messages from SUNI's own address go out only after an "
                f"administrator approves them in the admin panel. Tell the user "
                f"it is waiting for approval; do not say it was sent.")

    ok, result, mid = _deliver(cfg, to, subject, body, paths, user_id,
                               in_reply_to=in_reply_to, refs=refs)
    if ok and cfg.get("account", "suni") != "user":
        from . import mail_outbox
        mail_outbox.record_sent_id(mid)
        mail_outbox._audit(user_id, "mail.internal.sent", f"to {to}: {subject}")
    return result


def recipients(to: str) -> list[str]:
    from email.utils import getaddresses
    return [a.strip().lower() for _, a in getaddresses([to.replace(";", ",")]) if a.strip()]


def internal_addresses() -> set[str]:
    """Who SUNI may mail without an admin's approval: active system users, by
    the address an admin set on their account, and the configured
    notification recipient."""
    out: set[str] = set()
    try:
        from .. import auth as _auth
        out |= _auth.internal_addresses()
    except Exception:              # noqa: BLE001 — unknown means external
        pass
    nt = setting("notify_to", "SUNI_NOTIFY_TO", "").strip().lower()
    if nt:
        out.add(nt)
    return out


def all_internal(to: str) -> bool:
    """True only when EVERY recipient is internal. One outside address in the
    list sends the whole message for approval."""
    rcpt = recipients(to)
    if not rcpt:
        return False
    known = internal_addresses()
    return all(r in known for r in rcpt)


def deliver_as_suni(to: str, subject: str, body: str, attachments: list[str] | None = None, *,
                    in_reply_to: str = "", refs: str = "", user_id: str = "") -> tuple[bool, str, str]:
    """Send from SUNI's own mailbox. Called ONLY by mail_outbox.approve, after
    an admin has approved the draft. Returns (ok, result text, Message-ID)."""
    cfg = _cfg("")
    if not cfg:
        return False, "Email not configured — SUNI's mailbox has no SMTP account.", ""
    paths = _paths("", attachments)
    problem = _check_attachments(paths, user_id)
    if problem:
        return False, problem, ""
    return _deliver(cfg, to, subject, body, paths, user_id,
                    in_reply_to=in_reply_to, refs=refs)


def _paths(attachment_path: str = "", attachment_paths: list[str] | None = None) -> list[Path]:
    out: list[Path] = []
    if attachment_path:
        out.append(Path(attachment_path))
    for p in (attachment_paths or []):
        if p:
            out.append(Path(p))
    return out


def _check_attachments(paths: list[Path], user_id: str = "") -> str:
    missing = [str(p) for p in paths if not p.exists()]
    if missing:
        return f"Attachment(s) not found: {', '.join(missing)}"
    blocked = [str(p) for p in paths if not _validate_attachment(p, user_id)]
    if blocked:
        return f"Attachment(s) blocked — not in allowed directories or unsafe extension: {', '.join(blocked)}"
    return ""


def _deliver(cfg: dict, to: str, subject: str, body: str, paths: list[Path],
             user_id: str = "", *, in_reply_to: str = "", refs: str = "") -> tuple[bool, str, str]:
    from email.utils import make_msgid
    from html import escape
    note = _disclosure()
    # The body is the model's (or a person's) text: escaped, so it cannot
    # inject markup into the HTML part.
    html = f"""<!DOCTYPE html>
<html><head><meta charset="UTF-8"></head>
<body style="margin:0;padding:32px;background:#07071a;font-family:'Courier New',monospace;color:#ddd;max-width:620px">
  <p style="font-size:22px;letter-spacing:.3em;color:#c9a227;text-transform:uppercase;font-weight:bold;margin-bottom:24px">SUNI</p>
  <div style="white-space:pre-wrap;font-size:14px;line-height:1.7;color:#ccc">{escape(body)}</div>
  <hr style="border:none;border-top:1px solid #1a1a3e;margin:32px 0">
  <p style="color:#444;font-size:11px;margin:0">Sent by SUNI &lt;{escape(cfg['user'])}&gt;</p>
  <p style="color:#444;font-size:11px;margin:6px 0 0">{escape(note)}</p>
</body></html>"""
    # EU AI Act Art. 50: visible disclosure appended to the plain-text body.
    plain_body = f"{body}\n\n—\n{note}"
    try:
        outer = MIMEMultipart("mixed")
        outer["Subject"] = subject
        outer["From"]    = _from(cfg["user"])
        outer["To"]      = to
        mid = make_msgid(domain=cfg["user"].rsplit("@", 1)[-1] if "@" in cfg["user"] else None)
        outer["Message-ID"] = mid
        if in_reply_to:
            outer["In-Reply-To"] = in_reply_to
            outer["References"] = (refs + " " + in_reply_to).strip() if in_reply_to not in refs else refs
        _mark_ai_generated(outer)

        alt = MIMEMultipart("alternative")
        alt.attach(MIMEText(plain_body, "plain"))
        alt.attach(MIMEText(html, "html"))
        outer.attach(alt)
        for p in paths:
            outer.attach(_make_attachment(p))

        with smtplib.SMTP(cfg["host"], cfg["port"]) as s:
            s.ehlo(); s.starttls()
            s.login(cfg["user"], cfg["password"])
            s.sendmail(cfg["user"], recipients(to) or [to], outer.as_string())

        if paths:
            names = ", ".join(f"'{p.name}'" for p in paths)
            return True, f"Email sent to {to} with {len(paths)} attachment(s): {names}.", mid
        return True, f"Email sent to {to}.", mid
    except Exception as e:
        return False, f"Failed to send email: {e}", ""


def _safe_attach_roots(user_id: str = "") -> list[Path]:
    """Directories an attachment may come from.

    Resolved per call, not at import. As a module-level list this silently
    excluded global_output_dir: an operator who pointed generated files at
    D:/suni_out would find create_pdf writing there happily and send_email
    refusing to attach anything it produced — SUNI blocking its own output,
    with "not in allowed directories" as the only clue. It works on this
    instance solely because the directory falls back to Desktop, which is on
    the list by luck rather than design.
    """
    # The operator's personal folders are NOT here, for the same reason they
    # were removed from the download roots: "attach the file from my Desktop"
    # is a convenience for one person on one machine, and a way to post someone
    # else's private documents out of the building on a shared instance.
    roots = [
        Path("memory"),
        Path("files"),
    ]
    try:
        from ..user_settings import resolve_output_dir
        out_dir = resolve_output_dir(user_id)
        if out_dir:
            roots.append(Path(out_dir))
    except Exception:                      # noqa: BLE001 — never block a send
        pass
    return roots
_BLOCKED_EXTENSIONS = {
    ".exe", ".dll", ".bat", ".cmd", ".ps1", ".vbs", ".msi",
    ".pem", ".key", ".pfx", ".p12", ".env", ".reg",
}

def _validate_attachment(p: Path, user_id: str = "") -> bool:
    """Return True only if the file is in an allowed directory with a safe extension."""
    if p.suffix.lower() in _BLOCKED_EXTENSIONS:
        return False
    resolved = p.resolve()
    return any(
        str(resolved).lower().startswith(str(root.resolve()).lower())
        for root in _safe_attach_roots(user_id)
    )


def _make_attachment(path: Path) -> MIMEApplication:
    """Build a MIME attachment from a file path."""
    suffix = path.suffix.lower()
    subtype = {
        ".pdf":  "pdf",
        ".docx": "vnd.openxmlformats-officedocument.wordprocessingml.document",
        ".xlsx": "vnd.openxmlformats-officedocument.spreadsheetml.sheet",
        ".csv":  "csv",
        ".txt":  "plain",
        ".png":  "png",
        ".jpg":  "jpeg",
        ".jpeg": "jpeg",
    }.get(suffix, "octet-stream")
    part = MIMEApplication(path.read_bytes(), _subtype=subtype)
    part.add_header("Content-Disposition", "attachment", filename=path.name)
    return part


def is_configured(user_id: str = "") -> bool:
    return _cfg(user_id) is not None
